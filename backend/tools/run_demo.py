"""Runs a demonstration set of difficult integrals through the real engine and writes docs/DEMO_RESULTS.md.

Nothing here is hard-coded: every answer, classification, verification status and derivation below is computed
by the engine when this script runs.
"""
from __future__ import annotations

import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("INTEGRALIS_DEBUG", "")

from integralis import EngineOptions, render, solve  # noqa: E402

INDEFINITE = [
    "1/(x^4+1)", "sec(x)^3", "exp(2*x)*cos(3*x)", "x^3*sin(x)", "sqrt(x^2+2*x+5)", "1/(x*sqrt(x+1))", "ln(x)^2",
    "(x^2+1)/(x^3+3*x)", "1/(x^2*(x^2+1))", "sin(x)^4", "x^2/(x^2+4)^(3/2)", "1/(1+sqrt(x))", "tan(x)^3*sec(x)^3",
    "x*arctan(x)", "1/(1+sin(x))", "1/(sqrt(x)+x^(1/3))",
    "exp(-x^2)", "sin(x)/x", "exp(x)/x", "1/ln(x)", "x^x", "sin(sin(x))",
]
DEFINITE = [
    ("1/(2+cos(x))", "0", "2*pi"), ("exp(-x^2)", "0", "oo"), ("exp(-x^2)", "-oo", "oo"), ("ln(x)", "0", "1"),
    ("sin(x)/(sin(x)+cos(x))", "0", "pi/2"), ("sin(x)/x", "0", "oo"), ("1/(1+x^2)", "-oo", "oo"),
    ("1/(x*ln(x)^2)", "2", "oo"), ("1/sqrt(1-x^2)", "-1", "1"), ("x^2*exp(-x)", "0", "oo"),
    ("1/x", "-1", "1"), ("1/x^2", "0", "1"), ("tan(x)", "0", "pi/2"), ("1/x", "1", "oo"), ("x^3*cos(x)", "-2", "2"),
]
SHOW_STEPS = {"1/(x^4+1)", "sec(x)^3", "exp(2*x)*cos(3*x)", "x^3*sin(x)"}


def steps_md(steps, depth=0):
    out = []
    for s in steps:
        pad = "  " * depth
        t = s.title.text()
        eq = ""
        if s.after is not None:
            eq = (f"`{render.text(s.before)}` → `{render.text(s.after)}`" if s.before is not None
                  and render.text(s.before) != render.text(s.after) else f"`{render.text(s.after)}`")
        out.append(f"{pad}- **{t}** [{s.verification.value}] {eq}  \n{pad}  {s.explanation.text()}")
        out.extend(steps_md(s.substeps, depth + 1))
    return out


def row(r, expr, t):
    ans = r.to_dict()["answer"]
    return (f"| `{expr}` | {r.status.value} | {r.classification.value} | "
            f"{'`' + ans['text'] + '`' if ans else (r.message.text()[:70] + '…' if r.message else '')} | "
            f"{r.verification_status} | {r.derivation_level} | {t:.1f}s |")


def main():
    opts = EngineOptions(timeout_seconds=40)
    lines = ["# Demonstration set of difficult integrals", "",
             f"Generated by `python tools/run_demo.py` on {time.strftime('%Y-%m-%d')} — every value below was computed by the "
             "engine during that run (nothing is hard-coded).", "",
             "## Indefinite integrals", "",
             "| integrand | status | classification | antiderivative | verification | derivation | time |",
             "|---|---|---|---|---|---|---|"]
    details = []
    t_all = time.time()
    for e in INDEFINITE:
        t = time.time()
        r = solve(e, options=opts)
        lines.append(row(r, e, time.time() - t))
        if e in SHOW_STEPS and r.solved:
            details.append((f"∫ {e} dx", r))
    lines += ["", "## Definite and improper integrals", "",
              "| integral | status | classification | value | verification | derivation | time |", "|---|---|---|---|---|---|---|"]
    for e, lo, hi in DEFINITE:
        t = time.time()
        r = solve(e, lower=lo, upper=hi, options=opts)
        lines.append(row(r, f"∫[{lo}, {hi}] {e}", time.time() - t))
        if r.status.value == "divergent" and e in ("1/x",):
            details.append((f"∫[{lo},{hi}] {e} dx (divergent)", r))
        if e == "1/(2+cos(x))":
            details.append((f"∫[{lo},{hi}] {e} dx (spurious jump of the antiderivative)", r))
    lines += ["", "## Selected derivations (as the engine displays them)", ""]
    for title, r in details:
        lines += [f"### {title}", "", *steps_md(r.steps), ""]
    lines += ["", f"_Total run time: {time.time() - t_all:.0f}s._"]
    out = ROOT.parent / "docs" / "DEMO_RESULTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:60]))
    print("written", out)


if __name__ == "__main__":
    main()
